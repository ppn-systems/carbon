namespace Carbon.Graphics.Fonts;

/// <summary>
/// Defines horizontal alignment options for text rendering.
/// </summary>
public enum TextAlignment
{
    /// <summary>
    /// Aligns text to the left margin.
    /// </summary>
    Left = 0,

    /// <summary>
    /// Centers text horizontally within the bounding area.
    /// </summary>
    Center = 1,

    /// <summary>
    /// Aligns text to the right margin.
    /// </summary>
    Right = 2
}
