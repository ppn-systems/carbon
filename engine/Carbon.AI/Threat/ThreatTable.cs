using System;
using Carbon.Simulation.ECS;

namespace Carbon.AI.Threat;

/// <summary>
/// Per-NPC aggro / threat table tracking threat accumulated by hostile targets and selecting the top target.
/// </summary>
public sealed class ThreatTable
{
    private struct ThreatEntry
    {
        public Entity Target;
        public float Threat;
    }

    private ThreatEntry[] _entries = new ThreatEntry[8];
    private int _count;

    /// <summary>
    /// Gets the number of targets currently tracked in this table.
    /// </summary>
    public int Count => _count;

    /// <summary>
    /// Adds threat generated by <paramref name="target"/>, inserting an entry if absent.
    /// </summary>
    /// <param name="target">Hostile entity handle.</param>
    /// <param name="amount">Threat value to add.</param>
    public void AddThreat(Entity target, float amount)
    {
        if (!target.IsValid || amount <= 0f)
        {
            return;
        }

        for (int i = 0; i < _count; i++)
        {
            if (_entries[i].Target == target)
            {
                _entries[i].Threat += amount;
                return;
            }
        }

        if (_count >= _entries.Length)
        {
            Array.Resize(ref _entries, _entries.Length * 2);
        }

        _entries[_count++] = new ThreatEntry
        {
            Target = target,
            Threat = amount
        };
    }

    /// <summary>
    /// Removes <paramref name="target"/> from the threat table.
    /// </summary>
    /// <param name="target">Entity handle to remove.</param>
    /// <returns><see langword="true"/> if removed; otherwise, <see langword="false"/>.</returns>
    public bool RemoveTarget(Entity target)
    {
        for (int i = 0; i < _count; i++)
        {
            if (_entries[i].Target == target)
            {
                this.RemoveAt(i);
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Selects the alive, non-dead target with the highest accumulated threat while pruning invalid/dead entries.
    /// </summary>
    /// <param name="entities">Entity manager used to validate target life and health.</param>
    /// <returns>The highest-threat valid <see cref="Entity"/>, or <see cref="Entity.Null"/> if none remain.</returns>
    public Entity SelectHighestThreatTarget(EntityManager entities)
    {
        ArgumentNullException.ThrowIfNull(entities);

        Entity best = Entity.Null;
        float bestThreat = float.NegativeInfinity;

        for (int i = _count - 1; i >= 0; i--)
        {
            Entity candidate = _entries[i].Target;
            if (!entities.IsAlive(candidate) || (entities.HasHealth(candidate) && entities.GetHealth(candidate).IsDead))
            {
                this.RemoveAt(i);
                continue;
            }

            if (_entries[i].Threat > bestThreat)
            {
                bestThreat = _entries[i].Threat;
                best = candidate;
            }
        }

        return best;
    }

    /// <summary>
    /// Clears all entries from the threat table.
    /// </summary>
    public void Clear() => _count = 0;

    private void RemoveAt(int index)
    {
        int last = _count - 1;
        if (index != last)
        {
            _entries[index] = _entries[last];
        }

        _count--;
    }
}
