namespace Carbon.Maps.Building;

/// <summary>
/// Reserved <see cref="StructureRecord.OwnerId"/> values of world factions. Faction-owned structures are generated content
/// (villages): players may use them (open doors) but never deconstruct, damage or build over them.
/// Player owner ids are hashed from character ids and are never in the reserved range (<see cref="ToPlayerOwnerId"/>).
/// </summary>
public static class StructureOwners
{
    /// <summary>First reserved faction owner id. Every id at or above it belongs to a faction.</summary>
    public const ulong FactionRangeStart = 0xFFFF_FFFF_FFFF_FF00UL;

    /// <summary>Owner id of structures generated by villages.</summary>
    public const ulong Village = 0xFFFF_FFFF_FFFF_FF01UL;

    /// <summary>Gets whether <paramref name="ownerId"/> is a world faction rather than a player.</summary>
    /// <param name="ownerId">Owner id.</param>
    /// <returns><see langword="true"/> for faction-owned structures.</returns>
    public static bool IsFaction(ulong ownerId) => ownerId >= FactionRangeStart;

    /// <summary>Maps a raw player id hash into the player range (never 0, never a faction id).</summary>
    /// <param name="hash">Raw hash.</param>
    /// <returns>A player owner id.</returns>
    public static ulong ToPlayerOwnerId(ulong hash) => hash == 0UL ? 1UL : IsFaction(hash) ? hash & 0x7FFF_FFFF_FFFF_FFFFUL : hash;
}
