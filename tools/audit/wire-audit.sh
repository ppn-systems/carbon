#!/usr/bin/env bash
# Regenerates docs/audit/2026-11-wire-protocol-generated.md: every opcode with its sender and handler, and every
# [SerializeOrder] field with the side that writes it and the side that reads it (tools/audit/WireAudit).
#
#   tools/audit/wire-audit.sh            # write the generated appendix
#   tools/audit/wire-audit.sh --stdout   # print it instead
#
# The tool resolves library types from the build output, so the production solutions are built first.
set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"
if ! command -v dotnet >/dev/null 2>&1 && [ -x "$HOME/.dotnet/dotnet" ]; then
    export PATH="$HOME/.dotnet:$PATH"
fi

for sln in contracts/Carbon.Contracts.slnx engine/Carbon.Engine.slnx graphics/Carbon.Graphics.slnx \
           server/Carbon.Server.slnx desktop/Carbon.Desktop.slnx tools/audit/WireAudit/WireAudit.csproj; do
    dotnet build "$sln" -c Release -v quiet -nologo >/dev/null
done

render() {
    echo "# Wire Protocol Audit — Generated Tables"
    echo
    echo "Generated by \`tools/audit/wire-audit.sh\`. Do not edit by hand; the findings and how to read these tables are in"
    echo "[2026-11-wire-protocol.md](2026-11-wire-protocol.md)."
    echo
    dotnet artifacts/bin/WireAudit/release/WireAudit.dll "$REPO_ROOT"
}

if [ "${1:-}" = "--stdout" ]; then
    render
else
    render > docs/audit/2026-11-wire-protocol-generated.md
fi
